static uint8_t *fix_image(void)
{
    uint8_t *b = malloc(1024);
    for (int i = 0; i < 1020; i++) b[i] = (uint8_t)((i % 5) * 3 + 1);
    memcpy(b + 1020, fix_tail, 4);
    return b;
}

static uint8_t *dyn_image(void)
{
    static const char *const words[7] = { "fairchild", "channel", "fujinet", "videocart", "bios", "the", "of" };
    uint8_t *b = malloc(1024);
    uint32_t x = 1;
    int n = 0;
    while (n < 1020) {
        const char *w;
        x = x * 1103515245u + 12345u;
        w = words[(x >> 16) % 7];
        for (; *w && n < 1020; w++) b[n++] = (uint8_t)*w;
        if (n < 1020) b[n++] = ' ';
    }
    memcpy(b + 1020, dyn_tail, 4);
    return b;
}

/* ---- sessions -------------------------------------------------------------------- */

static chfsession *new_session(const char *tag, char *data, size_t datasz, char *work, size_t worksz)
{
    char cfg[300];
    chfsession_paths p;

    test_tmpdir(cfg, sizeof cfg, tag);
    snprintf(data, datasz, "%s/data", cfg);
    snprintf(work, worksz, "%s/in", cfg);
    mkpath(data);
    mkpath(work);
    memset(&p, 0, sizeof p);
    p.config_dir = cfg; p.data_dir = data; p.fujinet_lib = "";
    return chfsession_new(&p);
}

static int count_parts(const char *dir)
{
    DIR *d = opendir(dir);
    struct dirent *e;
    int n = 0;
    if (!d) return -1;
    while ((e = readdir(d)) != NULL)
        if (strstr(e->d_name, ".part")) n++;
    closedir(d);
    return n;
}

static int all_available(chfsession *s)
{
    for (int i = 0; i < CHF_ROM_COUNT; i++)
        if (!chfsession_rom_item_available(s, i)) return 0;
    return 1;
}

static int any_bios(chfsession *s)
{
    for (int m = 0; m < CHF_MACHINE_COUNT; m++)
        if (chfsession_have_bios(s, m)) return 1;
    return 0;
}

/* a 2K file: a first half and then sl31254 (or any two halves) */
static void write_pair(const char *path, int first, int second, uint32_t seed)
{
    uint8_t *a = item_image(first, seed), *b = item_image(second, seed + 1);
    uint8_t *both = malloc(2048);
    memcpy(both, a, 1024);
    memcpy(both + 1024, b, 1024);
    write_file(path, both, 2048);
    free(a); free(b); free(both);
}

int main(void)
{
    char data[400], work[400], path[800], dest[900], msg[1024];
    chfsession *s;
    uint8_t *buf;
    long n;
    int i, rc;

    crc_tables();
    check(crc_of((const uint8_t *)"123456789", 9) == 0xcbf43926u, "the test's CRC-32 is the standard one");
    check(zipread_crc32((const uint8_t *)"123456789", 9) == 0xcbf43926u, "and so is the reader's");

    /* ---- the table ---- */
    s = new_session("rom1", data, sizeof data, work, sizeof work);
    if (!s) return 1;
    check(chfsession_rom_item_count() == CHF_ROM_COUNT && CHF_ROM_COUNT == 3, "three ROM items");
    for (i = 0; i < CHF_ROM_COUNT; i++) {
        const chf_rom_item *it = chfsession_rom_item(i);
        char what[96];
        snprintf(what, sizeof what, "item %d is %s, %u bytes, CRC %08x", i, k_items[i].file,
                 (unsigned)k_items[i].size, (unsigned)k_items[i].crc);
        check(it && !strcmp(it->file, k_items[i].file) && it->size == k_items[i].size
              && it->crc == k_items[i].crc && it->name && strstr(it->name, k_items[i].file) && it->group, what);
    }
    check(chfsession_rom_item(-1) == NULL && chfsession_rom_item(CHF_ROM_COUNT) == NULL, "no item out of range");
    check(!strcmp(chfsession_rom_item(CHF_ROM_SL31253)->name, "Channel F BIOS, first half (sl31253.rom)")
          && !strcmp(chfsession_rom_item(CHF_ROM_SL31253)->group, "Console"), "named and grouped for the Preferences list");
    check(strncmp(chfsession_roms_path(s), data, strlen(data)) == 0, "the ROM directory is under the data tree");
    check(!any_bios(s) && !all_available(s) && chfsession_bios_in_use(s) == -1, "nothing is imported yet");
    for (i = 0; i < CHF_BIOS_CHOICE_COUNT; i++)
        if (!chf_bios_choice_name(i)[0]) break;
    check(i == CHF_BIOS_CHOICE_COUNT, "every BIOS choice has a name");

    /* ---- one file, any name ---- */
    snprintf(path, sizeof path, "%s/Fairchild Channel F BIOS (1976).bin", work);
    write_item(path, CHF_ROM_SL31253, 1);
    check(chfsession_media_is_rom(path), "a BIOS dump is recognised as a ROM by size and CRC");
    rc = chfsession_rom_import(s, path, msg, sizeof msg);
    check(rc == 1, "importing it takes one item");
    check(strstr(msg, "sl31253.rom") != NULL && strstr(msg, "next power cycle") != NULL, "and says what and when");
    check(strstr(msg, "sl31254.rom") != NULL, "and that the second half is still missing");
    snprintf(dest, sizeof dest, "%s/sl31253.rom", chfsession_roms_path(s));
    check(size_of(dest) == 1024, "it is stored as MAME's sl31253.rom");
    buf = read_all(dest, &n);
    check(n == 1024 && crc_of(buf, 1024) == 0x04694ed9u, "byte for byte");
    free(buf);
    check(count_parts(chfsession_roms_path(s)) == 0, "with no .part file left behind");
    check(chfsession_rom_item_available(s, CHF_ROM_SL31253) && !chfsession_rom_item_available(s, CHF_ROM_SL31254),
          "the item list says so");
    check(!any_bios(s), "a first half alone is not a BIOS");

    /* importing twice is harmless */
    snprintf(path, sizeof path, "%s/again.rom", work);
    write_item(path, CHF_ROM_SL31253, 2);
    check(chfsession_rom_import(s, path, msg, sizeof msg) == 1, "the same ROM under another name imports");
    check(count_parts(chfsession_roms_path(s)) == 0 && size_of(dest) == 1024, "importing twice is harmless");

    /* ---- every item ---- */
    for (i = 0; i < CHF_ROM_COUNT; i++) {
        char name[600], what[160];
        snprintf(name, sizeof name, "%s/dump-%d.dat", work, i);
        write_item(name, i, 100 + (uint32_t)i);
        rc = chfsession_rom_import(s, name, msg, sizeof msg);
        snprintf(dest, sizeof dest, "%s/%s", chfsession_roms_path(s), k_items[i].file);
        snprintf(what, sizeof what, "%s imports under its own name", k_items[i].file);
        check(rc == 1 && size_of(dest) == (long)k_items[i].size && chfsession_rom_item_available(s, i), what);
    }
    check(all_available(s), "all three are in the ROM directory");
    check(strstr(msg, "needs") == NULL, "with nothing left to ask for");

    /* ---- which BIOS runs on which machine ---- */
    check(chfsession_have_bios(s, CHF_MACHINE_CHANNELF) && chfsession_have_bios(s, CHF_MACHINE_CHANNELF2)
          && chfsession_have_bios(s, CHF_MACHINE_VIDEOPLAY) && chfsession_have_bios(s, CHF_MACHINE_VIDEOPLAY2),
          "with everything imported every machine has a BIOS");
    chfsession_set_int(s, "bios", CHF_BIOS_STANDIN);
    check(!any_bios(s), "the stand-in choice runs no real BIOS");
    chfsession_set_int(s, "bios", CHF_BIOS_SL90025);
    check(chfsession_have_bios(s, CHF_MACHINE_CHANNELF), "sl90025 chosen: the Channel F runs it");
    chfsession_set_int(s, "bios", CHF_BIOS_AUTO);

    /* ---- the first halves are each other's fallback; sl31254 is needed either way ---- */
    chfsession_free(s);
    s = new_session("rom2", data, sizeof data, work, sizeof work);
    snprintf(path, sizeof path, "%s/lo.bin", work);
    write_item(path, CHF_ROM_SL90025, 5);
    check(chfsession_rom_import(s, path, msg, sizeof msg) == 1 && !any_bios(s), "sl90025 alone: no BIOS yet");
    check(strstr(msg, "sl31254.rom") != NULL && strstr(msg, "first half") == NULL,
          "it asks for sl31254, not for a first half");
    snprintf(path, sizeof path, "%s/hi.bin", work);
    write_item(path, CHF_ROM_SL31254, 6);
    check(chfsession_rom_import(s, path, msg, sizeof msg) == 1, "sl31254 joins it");
    check(chfsession_have_bios(s, CHF_MACHINE_CHANNELF2) && chfsession_have_bios(s, CHF_MACHINE_VIDEOPLAY2),
          "the System II and the Videoplay 2 have their own");
    check(chfsession_have_bios(s, CHF_MACHINE_CHANNELF) && chfsession_have_bios(s, CHF_MACHINE_VIDEOPLAY),
          "the Channel F and the Videoplay fall back to the other first half");
    chfsession_set_int(s, "bios", CHF_BIOS_SL31253);
    check(!chfsession_have_bios(s, CHF_MACHINE_CHANNELF2), "choosing the half that is not there runs the stand-in");
    chfsession_set_int(s, "bios", CHF_BIOS_AUTO);

    /* the other way: only sl31253 and sl31254 */
    chfsession_free(s);
    s = new_session("rom3", data, sizeof data, work, sizeof work);
    snprintf(path, sizeof path, "%s/a.bin", work);
    write_item(path, CHF_ROM_SL31254, 7);
    rc = chfsession_rom_import(s, path, msg, sizeof msg);
    check(rc == 1 && strstr(msg, "first half") != NULL && !any_bios(s), "sl31254 alone asks for a first half");
    snprintf(path, sizeof path, "%s/b.bin", work);
    write_item(path, CHF_ROM_SL31253, 8);
    chfsession_rom_import(s, path, msg, sizeof msg);
    check(chfsession_have_bios(s, CHF_MACHINE_CHANNELF2), "the System II falls back to sl31253");

    /* ---- a 2K file: a known first half followed by sl31254 is split ---- */
    chfsession_free(s);
    s = new_session("rom4", data, sizeof data, work, sizeof work);
    snprintf(path, sizeof path, "%s/bios2k.bin", work);
    write_pair(path, CHF_ROM_SL90025, CHF_ROM_SL31254, 20);
    check(chfsession_media_is_rom(path), "a 2K first half + sl31254 is a ROM");
    rc = chfsession_rom_import(s, path, msg, sizeof msg);
    check(rc == 2 && chfsession_rom_item_available(s, CHF_ROM_SL90025) && chfsession_rom_item_available(s, CHF_ROM_SL31254)
          && !chfsession_rom_item_available(s, CHF_ROM_SL31253), "it is split into sl90025.rom and sl31254.rom");
    check(strstr(msg, "sl90025.rom") && strstr(msg, "sl31254.rom") && any_bios(s), "the message names both, and there is a BIOS");
    snprintf(dest, sizeof dest, "%s/sl90025.rom", chfsession_roms_path(s));
    buf = read_all(dest, &n);
    check(n == 1024 && crc_of(buf, 1024) == 0x015c1e38u, "each half byte for byte");
    free(buf);
    /* two first halves, or sl31254 first, are not a BIOS */
    snprintf(path, sizeof path, "%s/wrong1.bin", work);
    write_pair(path, CHF_ROM_SL31253, CHF_ROM_SL90025, 30);
    check(!chfsession_media_is_rom(path) && chfsession_rom_import(s, path, msg, sizeof msg) == 0,
          "two first halves are not a BIOS");
    snprintf(path, sizeof path, "%s/wrong2.bin", work);
    write_pair(path, CHF_ROM_SL31254, CHF_ROM_SL31253, 31);
    check(!chfsession_media_is_rom(path) && chfsession_rom_import(s, path, msg, sizeof msg) == 0,
          "sl31254 first is not a BIOS");
    {
        uint8_t unknown2k[2048];
        for (i = 0; i < 2048; i++) unknown2k[i] = (uint8_t)(i * 5 + 1);
        snprintf(path, sizeof path, "%s/unknown2k.bin", work);
        write_file(path, unknown2k, sizeof unknown2k);
        rc = chfsession_rom_import(s, path, msg, sizeof msg);
        check(rc == 0 && !chfsession_media_is_rom(path) && strstr(msg, "2048 bytes") != NULL,
              "an unrecognised 2K file is refused, with its size");
    }

    /* ---- an unknown 1K file is never taken ---- */
    chfsession_free(s);
    s = new_session("rom5", data, sizeof data, work, sizeof work);
    {
        uint8_t unknown[1024];
        for (i = 0; i < 1024; i++) unknown[i] = (uint8_t)(i * 7 + 3);
        check(identify_none(unknown), "the filler is none of the three");

        /* handed over alone */
        snprintf(path, sizeof path, "%s/patched.bin", work);
        write_file(path, unknown, 1024);
        check(!chfsession_media_is_rom(path), "a dropped unknown 1K file is left for the cartridge path");
        rc = chfsession_rom_import(s, path, msg, sizeof msg);
        check(rc == 0 && !chfsession_rom_item_available(s, CHF_ROM_SL31253)
              && !chfsession_rom_item_available(s, CHF_ROM_SL90025) && !chfsession_rom_item_available(s, CHF_ROM_SL31254),
              "handed over alone it is still refused: it could be either first half");
        {
            char want[16];
            snprintf(want, sizeof want, "%08X", (unsigned)crc_of(unknown, 1024));
            check(strstr(msg, want) != NULL && strstr(msg, "1024 bytes") != NULL && strstr(msg, "patched.bin") != NULL,
                  "and the message names the file, its size and its CRC");
            check(strstr(msg, "channelf.zip") != NULL, "and where the ROMs come from");
        }
        check(count_parts(chfsession_roms_path(s)) == 0, "nothing was written");

        /* alone in a folder */
        snprintf(path, sizeof path, "%s/sweep", work);
        mkpath(path);
        snprintf(dest, sizeof dest, "%s/unknown.bin", path);
        write_file(dest, unknown, 1024);
        rc = chfsession_rom_import(s, path, msg, sizeof msg);
        check(rc == 0 && strstr(msg, "No Channel F") != NULL, "a folder sweep does not take it, and says nothing was found");

        /* in a zip */
        {
            zent z[1];
            z[0] = stored_bytes("mystery.bin", unknown, 1024);
            snprintf(dest, sizeof dest, "%s/mystery.zip", work);
            write_zip(dest, z, 1);
            check(!chfsession_media_is_rom(dest), "a zip of unknowns is not a ROM zip");
            rc = chfsession_rom_import(s, dest, msg, sizeof msg);
            check(rc == 0 && !chfsession_rom_item_available(s, CHF_ROM_SL31253), "nor is an unknown file in a zip");
        }

        /* any other size is not a ROM at all */
        {
            uint8_t odd[1000];
            memset(odd, 0x55, sizeof odd);
            snprintf(path, sizeof path, "%s/odd.bin", work);
            write_file(path, odd, sizeof odd);
            rc = chfsession_rom_import(s, path, msg, sizeof msg);
            check(rc == 0 && strstr(msg, "1000 bytes") != NULL && strstr(msg, "odd.bin") != NULL,
                  "a 1000-byte file is refused, with its size");
            check(!chfsession_media_is_rom(path), "and is not a ROM");
        }
    }

    /* ---- a zip, stored: MAME's channelf.zip has all three ---- */
    chfsession_free(s);
    s = new_session("rom6", data, sizeof data, work, sizeof work);
    {
        zent z[4];
        uint8_t other[100];
        memset(other, 3, sizeof other);
        z[0] = stored_item("sl31253.rom", CHF_ROM_SL31253, 11);
        z[1] = stored_item("sl31254.rom", CHF_ROM_SL31254, 12);
        z[2] = stored_item("sub/dir/sl31254-again.rom", CHF_ROM_SL31254, 13);   /* same CRC: counted once */
        z[3] = stored_bytes("readme.txt", other, sizeof other);
        snprintf(dest, sizeof dest, "%s/channelf.zip", work);
        write_zip(dest, z, 4);
        check(chfsession_media_is_rom(dest), "a zip with a ROM in it is a ROM");
        rc = chfsession_rom_import(s, dest, msg, sizeof msg);
        check(rc == 2 && any_bios(s), "the stored zip's two ROMs are imported (a duplicate counted once)");
        check(strstr(msg, "sl31253.rom") && strstr(msg, "sl31254.rom") && !strstr(msg, "sl90025"), "the message names them");
        free_stored();
    }

    /* ---- a zip, deflated: fixed and dynamic Huffman ---- */
    chfsession_free(s);
    s = new_session("rom7", data, sizeof data, work, sizeof work);
    {
        uint8_t *fi = fix_image(), *di = dyn_image();
        uint8_t out[1024];
        zent z[2];

        check(crc_of(fi, 1024) == 0x9c047ba3u && crc_of(di, 1024) == 0x04694ed9u,
              "the fixtures decompress to ROMs of the importer's table");
        check(zipread_inflate(fix_stream, sizeof fix_stream, out, 1024) == 0 && memcmp(out, fi, 1024) == 0,
              "inflate: the fixed-Huffman stream");
        check(zipread_inflate(dyn_stream, sizeof dyn_stream, out, 1024) == 0 && memcmp(out, di, 1024) == 0,
              "inflate: the dynamic-Huffman stream");
        check(zipread_inflate(dyn_stream, sizeof dyn_stream - 20, out, 1024) != 0, "inflate: a truncated stream fails");
        check(zipread_inflate(dyn_stream, sizeof dyn_stream, out, 1023) != 0, "inflate: output over the stated size fails");
        {
            uint8_t big[1025];
            check(zipread_inflate(dyn_stream, sizeof dyn_stream, big, 1025) != 0, "inflate: output short of the stated size fails");
        }
        {
            uint8_t bad[sizeof dyn_stream];
            memcpy(bad, dyn_stream, sizeof bad);
            bad[0] |= 6;           /* block type 3 is invalid */
            check(zipread_inflate(bad, sizeof bad, out, 1024) != 0, "inflate: a reserved block type fails");
        }
        {   /* a stored block: BFINAL=1 BTYPE=0, LEN=5, NLEN=~5, "hello" */
            static const uint8_t st[] = { 0x01, 0x05, 0x00, 0xfa, 0xff, 'h', 'e', 'l', 'l', 'o' };
            check(zipread_inflate(st, sizeof st, out, 5) == 0 && !memcmp(out, "hello", 5), "inflate: a stored block");
        }

        z[0].name = "sl31254.rom"; z[0].data = fix_stream; z[0].csize = sizeof fix_stream;
        z[0].usize = 1024; z[0].crc = 0x9c047ba3u; z[0].method = 8;
        z[1].name = "sl31253.rom"; z[1].data = dyn_stream; z[1].csize = sizeof dyn_stream;
        z[1].usize = 1024; z[1].crc = 0x04694ed9u; z[1].method = 8;
        snprintf(dest, sizeof dest, "%s/deflated.zip", work);
        write_zip(dest, z, 2);
        check(chfsession_media_is_rom(dest), "a deflated zip is recognised");
        rc = chfsession_rom_import(s, dest, msg, sizeof msg);
        check(rc == 2 && any_bios(s), "both deflated entries import");
        snprintf(path, sizeof path, "%s/sl31254.rom", chfsession_roms_path(s));
        buf = read_all(path, &n);
        check(n == 1024 && memcmp(buf, fi, 1024) == 0, "the fixed-Huffman entry, byte for byte");
        free(buf);
        snprintf(path, sizeof path, "%s/sl31253.rom", chfsession_roms_path(s));
        buf = read_all(path, &n);
        check(n == 1024 && memcmp(buf, di, 1024) == 0, "the dynamic-Huffman entry, byte for byte");
        free(buf);

        /* a corrupt entry (CRC wrong) is skipped, not imported */
        z[0].crc = 0x12345678u;
        chfsession_free(s);
        s = new_session("rom7b", data, sizeof data, work, sizeof work);
        snprintf(dest, sizeof dest, "%s/corrupt.zip", work);
        write_zip(dest, z, 1);
        rc = chfsession_rom_import(s, dest, msg, sizeof msg);
        check(rc == 0 && !chfsession_rom_item_available(s, CHF_ROM_SL31254), "a zip entry whose CRC is wrong is not imported");
        free(fi);
        free(di);
    }

    /* ---- a folder, eight levels deep, with zips in it ---- */
    chfsession_free(s);
    s = new_session("rom8", data, sizeof data, work, sizeof work);
    {
        char deep[600];
        snprintf(deep, sizeof deep, "%s/pile", work);
        for (i = 0; i < 8; i++) {
            char seg[16];
            snprintf(seg, sizeof seg, "/d%d", i);
            strcat(deep, seg);
        }
        mkpath(deep);
        snprintf(path, sizeof path, "%s/sl31253.rom", deep);
        write_item(path, CHF_ROM_SL31253, 21);                   /* 8 levels down: found */
        snprintf(path, sizeof path, "%s/pile/d0/d1/readme.txt", work);
        write_file(path, "hi", 2);
        snprintf(path, sizeof path, "%s/pile/d0/hi.bin", work);
        write_item(path, CHF_ROM_SL31254, 22);                   /* one level down */

        strcat(deep, "/d8");
        mkpath(deep);
        snprintf(path, sizeof path, "%s/sl90025.rom", deep);
        write_item(path, CHF_ROM_SL90025, 23);                   /* 9 levels down: not found */

        {
            zent z[1];
            z[0] = stored_item("sl31254.rom", CHF_ROM_SL31254, 24);
            snprintf(path, sizeof path, "%s/pile/d0/d1/inner.zip", work);
            write_zip(path, z, 1);                               /* a zip inside the folder */
            free_stored();
        }
        snprintf(path, sizeof path, "%s/pile", work);
        check(!chfsession_media_is_rom(path), "a folder is not itself a dropped ROM");
        rc = chfsession_rom_import(s, path, msg, sizeof msg);
        check(rc == 2, "the folder: the first half 8 levels down, and sl31254 (loose and in the zip, once)");
        check(chfsession_rom_item_available(s, CHF_ROM_SL31253) && chfsession_rom_item_available(s, CHF_ROM_SL31254)
              && any_bios(s), "both are there");
        check(!chfsession_rom_item_available(s, CHF_ROM_SL90025), "the one 9 levels down is not");
        check(strstr(msg, "sl31253.rom") && strstr(msg, "sl31254.rom"), "the message names what it found");

        /* a zip in a zip */
        {
            zent inner[1], outer[1];
            uint8_t *img = item_image(CHF_ROM_SL90025, 25);
            uint8_t zbytes[4096];
            long zn;
            FILE *f;

            inner[0] = stored_bytes("sl90025.rom", img, 1024);
            snprintf(path, sizeof path, "%s/inner2.zip", work);
            write_zip(path, inner, 1);
            f = fopen(path, "rb");
            zn = (long)fread(zbytes, 1, sizeof zbytes, f);
            fclose(f);
            outer[0] = stored_bytes("inner.zip", zbytes, (uint32_t)zn);
            snprintf(path, sizeof path, "%s/outer.zip", work);
            write_zip(path, outer, 1);
            check(chfsession_media_is_rom(path), "a zip inside a zip is looked into");
            rc = chfsession_rom_import(s, path, msg, sizeof msg);
            check(rc == 1 && chfsession_rom_item_available(s, CHF_ROM_SL90025), "and its ROM imports");
            free(img);
        }

        /* the import_media route: a dropped ROM goes to the ROM directory */
        snprintf(path, sizeof path, "%s/pile/d0/hi.bin", work);
        check(chfsession_import_media(s, path, dest, sizeof dest) == 0
              && strstr(dest, "sl31254.rom") != NULL, "a dropped ROM is routed to the ROM directory");
        check(!chfsession_media_is_cartridge(path), "and is not a cartridge though it is a .bin");
        snprintf(path, sizeof path, "%s/pile/d0/d1/inner.zip", work);
        check(chfsession_import_media(s, path, dest, sizeof dest) == 0 && strcmp(dest, "") != 0
              && !chfsession_media_is_cartridge(path), "so is a dropped zip of ROMs");
    }

    /* ---- nothing there, and nothing to read ---- */
    chfsession_free(s);
    s = new_session("rom9", data, sizeof data, work, sizeof work);
    snprintf(path, sizeof path, "%s/none", work);
    mkpath(path);
    rc = chfsession_rom_import(s, path, msg, sizeof msg);
    check(rc == 0 && msg[0], "an empty folder: nothing recognised, and it says so");
    snprintf(path, sizeof path, "%s/does-not-exist", work);
    rc = chfsession_rom_import(s, path, msg, sizeof msg);
    check(rc == -1 && strstr(msg, "does-not-exist") != NULL, "a missing path is an error");
    check(strstr(chfsession_last_error(s), "does-not-exist") != NULL, "and the session's error says so too");
    check(chfsession_rom_import(s, "", msg, sizeof msg) == -1 && chfsession_rom_import(s, NULL, msg, sizeof msg) == -1,
          "an empty path is an error");
    check(!chfsession_media_is_rom(path) && !chfsession_media_is_rom(NULL) && !chfsession_media_is_rom(""),
          "none of them is a ROM");
    snprintf(path, sizeof path, "%s/notazip.zip", work);
    write_file(path, "PK this is not really a zip, whatever it is called", 51);
    check(chfsession_rom_import(s, path, msg, sizeof msg) == 0, "a file called .zip that is not one is just a file");

    /* ---- CHF_ROM_DIR moves the ROM directory (the tests' own override) ---- */
    {
        char alt[600], cfg[300];
        chfsession_paths p;
        chfsession *s2;

        test_tmpdir(cfg, sizeof cfg, "rom10");
        snprintf(alt, sizeof alt, "%s/elsewhere/roms", cfg);
#if defined(_WIN32)
        _putenv_s("CHF_ROM_DIR", alt);
#else
        setenv("CHF_ROM_DIR", alt, 1);
#endif
        snprintf(data, sizeof data, "%s/data", cfg);
        memset(&p, 0, sizeof p);
        p.config_dir = cfg; p.data_dir = data; p.fujinet_lib = "";
        s2 = chfsession_new(&p);
        check(s2 && strcmp(chfsession_roms_path(s2), alt) == 0, "CHF_ROM_DIR is the ROM directory");
        snprintf(path, sizeof path, "%s/bios.bin", cfg);
        write_item(path, CHF_ROM_SL31253, 31);
        if (s2) {
            check(chfsession_rom_import(s2, path, msg, sizeof msg) == 1, "an import lands there");
            snprintf(dest, sizeof dest, "%s/sl31253.rom", alt);
            check(size_of(dest) == 1024 && chfsession_rom_item_available(s2, CHF_ROM_SL31253), "and is found there");
            chfsession_free(s2);
        }
#if defined(_WIN32)
        _putenv_s("CHF_ROM_DIR", "");
#else
        unsetenv("CHF_ROM_DIR");
#endif
    }

    /* ---- MAME's own channelf.zip, when it is here ---- */
    {
        const char *mame = getenv("CHF_MAME_ROMS");
        char zip[900];

        chfsession_free(s);
        s = new_session("rom11", data, sizeof data, work, sizeof work);
        if (mame && *mame)
            snprintf(zip, sizeof zip, "%s/channelf.zip", mame);
        else
            snprintf(zip, sizeof zip, "%s/Workspace/mame/roms/channelf.zip", getenv("HOME") ? getenv("HOME") : ".");
        if (exists(zip)) {
            check(chfsession_media_is_rom(zip), "MAME's channelf.zip is a ROM zip");
            rc = chfsession_rom_import(s, zip, msg, sizeof msg);
            check(rc == 3 && all_available(s), "and imports all three ROMs");
            check(chfsession_have_bios(s, CHF_MACHINE_CHANNELF) && chfsession_have_bios(s, CHF_MACHINE_VIDEOPLAY2),
                  "every machine has a BIOS from it");
        } else {
            printf("SKIP: no MAME channelf.zip at %s\n", zip);
        }
    }

    chfsession_free(s);
    printf("%d failure(s)\n", failures);
    return failures ? 1 : 0;
}
