static int failures;
static void check(int ok, const char *what)
{
    printf("%s: %s\n", ok ? "ok" : "FAIL", what);
    if (!ok) failures++;
}

/* ---- the table the importer must carry (MAME's) ---------------------------- */

static const struct {
    const char *file;
    uint32_t size, crc;
} k_items[CHF_ROM_COUNT] = {
    [CHF_ROM_SL31253] = { "sl31253.rom", 1024, 0x04694ed9u },
    [CHF_ROM_SL90025] = { "sl90025.rom", 1024, 0x015c1e38u },
    [CHF_ROM_SL31254] = { "sl31254.rom", 1024, 0x9c047ba3u },
};

/* ---- CRC-32, and filler with a chosen one --------------------------------- */

static uint32_t T[256];
static uint8_t inv[256];        /* T's top bytes are a permutation */

static void crc_tables(void)
{
    for (uint32_t i = 0; i < 256; i++) {
        uint32_t c = i;
        for (int k = 0; k < 8; k++)
            c = (c >> 1) ^ (0xedb88320u & (~(c & 1) + 1));
        T[i] = c;
        inv[c >> 24] = (uint8_t)i;
    }
}

static uint32_t crc_of(const uint8_t *p, size_t n)
{
    uint32_t r = 0xffffffffu;
    while (n--)
        r = (r >> 8) ^ T[(r ^ *p++) & 0xff];
    return ~r;
}

/* `size` bytes of seeded filler ending in the four bytes that make the CRC-32
 * `want`: pick the four table entries whose sum is the final register, then
 * the bytes that select them from the register the filler leaves. */
static void forge(uint8_t *buf, uint32_t size, uint32_t seed, uint32_t want)
{
    uint32_t r = 0xffffffffu, v = ~want;
    uint8_t idx[4];

    for (uint32_t i = 0; i < size - 4; i++) {
        seed = seed * 1103515245u + 12345u;
        buf[i] = (uint8_t)(seed >> 16);
        r = (r >> 8) ^ T[(r ^ buf[i]) & 0xff];
    }
    idx[3] = inv[v >> 24];          v ^= T[idx[3]];
    idx[2] = inv[(v >> 16) & 0xff]; v ^= T[idx[2]] >> 8;
    idx[1] = inv[(v >> 8) & 0xff];  v ^= T[idx[1]] >> 16;
    idx[0] = inv[v & 0xff];
    for (int k = 0; k < 4; k++) {
        buf[size - 4 + k] = (uint8_t)(idx[k] ^ (r & 0xff));
        r = (r >> 8) ^ T[idx[k]];
    }
}

/* ---- files, folders, zips ---------------------------------------------------- */

static int exists(const char *p) { struct stat st; return stat(p, &st) == 0; }

static long size_of(const char *p)
{
    struct stat st;
    return stat(p, &st) == 0 ? (long)st.st_size : -1;
}

static void write_file(const char *path, const void *data, size_t n)
{
    FILE *f = fopen(path, "wb");
    if (!f) { printf("FAIL: cannot write %s\n", path); failures++; return; }
    fwrite(data, 1, n, f);
    fclose(f);
}

static void mkpath(const char *dir)
{
    char buf[1024];
    char *p;
    snprintf(buf, sizeof buf, "%s", dir);
    for (p = buf + 1; *p; p++)
        if (*p == '/') {
            *p = '\0';
            test_mkdir(buf);
            *p = '/';
        }
    test_mkdir(buf);
}

/* An image of item `id`, forged. Caller frees. */
static uint8_t *item_image(int id, uint32_t seed)
{
    uint8_t *b = malloc(k_items[id].size);
    forge(b, k_items[id].size, seed, k_items[id].crc);
    return b;
}

static void write_item(const char *path, int id, uint32_t seed)
{
    uint8_t *b = item_image(id, seed);
    write_file(path, b, k_items[id].size);
    free(b);
}

static uint8_t *read_all(const char *path, long *n)
{
    FILE *f = fopen(path, "rb");
    uint8_t *b;
    if (!f) { *n = -1; return NULL; }
    fseek(f, 0, SEEK_END);
    *n = ftell(f);
    fseek(f, 0, SEEK_SET);
    b = malloc((size_t)*n + 1);
    if (fread(b, 1, (size_t)*n, f) != (size_t)*n) *n = -1;
    fclose(f);
    return b;
}

static void put16(uint8_t *p, unsigned v) { p[0] = (uint8_t)v; p[1] = (uint8_t)(v >> 8); }
static void put32(uint8_t *p, uint32_t v) { for (int i = 0; i < 4; i++) p[i] = (uint8_t)(v >> (8 * i)); }

typedef struct {
    const char *name;
    const uint8_t *data;       /* what the entry holds (stored) or the deflate stream */
    uint32_t csize;            /* bytes in the file */
    uint32_t usize, crc;
    int method;                /* 0 stored, 8 deflated */
} zent;

/* A zip, the way `zip` writes one: local headers, the central directory, the
 * end record. */
static void write_zip(const char *path, const zent *e, int n)
{
    FILE *f = fopen(path, "wb");
    uint32_t off[16], cd_off, cd_size = 0;
    uint8_t h[46];
    int i;

    if (!f) { printf("FAIL: cannot write %s\n", path); failures++; return; }
    for (i = 0; i < n; i++) {
        size_t nl = strlen(e[i].name);
        off[i] = (uint32_t)ftell(f);
        memset(h, 0, sizeof h);
        put32(h, 0x04034b50u); put16(h + 4, 20); put16(h + 8, (unsigned)e[i].method);
        put16(h + 12, 0x21); put32(h + 14, e[i].crc);
        put32(h + 18, e[i].csize); put32(h + 22, e[i].usize); put16(h + 26, (unsigned)nl);
        fwrite(h, 1, 30, f);
        fwrite(e[i].name, 1, nl, f);
        fwrite(e[i].data, 1, e[i].csize, f);
    }
    cd_off = (uint32_t)ftell(f);
    for (i = 0; i < n; i++) {
        size_t nl = strlen(e[i].name);
        memset(h, 0, sizeof h);
        put32(h, 0x02014b50u); put16(h + 4, 20); put16(h + 6, 20); put16(h + 10, (unsigned)e[i].method);
        put16(h + 14, 0x21); put32(h + 16, e[i].crc);
        put32(h + 20, e[i].csize); put32(h + 24, e[i].usize); put16(h + 28, (unsigned)nl);
        put32(h + 42, off[i]);
        fwrite(h, 1, 46, f);
        fwrite(e[i].name, 1, nl, f);
        cd_size += 46 + (uint32_t)nl;
    }
    memset(h, 0, 22);
    put32(h, 0x06054b50u); put16(h + 8, (unsigned)n); put16(h + 10, (unsigned)n);
    put32(h + 12, cd_size); put32(h + 16, cd_off);
    fwrite(h, 1, 22, f);
    fclose(f);
}

/* Entries for forged items, stored. The images live until free_stored(). */
static uint8_t *g_img[16];
static int g_nimg;

static zent stored_item(const char *name, int id, uint32_t seed)
{
    zent z;
    uint8_t *b = item_image(id, seed);
    g_img[g_nimg++] = b;
    z.name = name; z.data = b; z.csize = z.usize = k_items[id].size;
    z.crc = k_items[id].crc; z.method = 0;
    return z;
}

static void free_stored(void)
{
    while (g_nimg > 0) free(g_img[--g_nimg]);
}

static zent stored_bytes(const char *name, const uint8_t *data, uint32_t n)
{
    zent z;
    z.name = name; z.data = data; z.csize = z.usize = n;
    z.crc = crc_of(data, n); z.method = 0;
    return z;
}

/* 1 if the 1K buffer's CRC-32 is none of the three ROMs' */
static int identify_none(const uint8_t *b)
{
    uint32_t crc = crc_of(b, 1024);
    for (int i = 0; i < CHF_ROM_COUNT; i++)
        if (crc == k_items[i].crc) return 0;
    return 1;
}

