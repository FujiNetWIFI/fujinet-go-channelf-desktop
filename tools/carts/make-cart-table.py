#!/usr/bin/env python3
"""make-cart-table.py -- generate core/chf/carts_table.h from MAME's Channel F
software list (hash/channelf.xml).

    make-cart-table.py [PATH/TO/channelf.xml] > core/chf/carts_table.h

Only what identifies a cartridge goes in: the ROM image's CRC-32 and size, the
PCB the list assigns it (the `slot` feature: std, maze, hangman, chess,
multi_old, multi), the list's short name and its description. Never ROM bytes.
core/chf/carts.c picks the Videocart type from it, so a game needs no hint.

MAME's hash files are CC0-1.0.
"""
import os
import sys
import xml.etree.ElementTree as ET

DEFAULT = os.path.expanduser("~/Workspace/mame/hash/channelf.xml")
TYPES = {"std": "CHF_CART_STD", "maze": "CHF_CART_MAZE", "hangman": "CHF_CART_HANGMAN",
         "chess": "CHF_CART_CHESS", "multi_old": "CHF_CART_MULTI_OLD", "multi": "CHF_CART_MULTI"}


def cstr(s):
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            # keep the table 7-bit: UTF-8 bytes as octal escapes
            out.extend("\\%03o" % b for b in ch.encode("utf-8"))
    return '"%s"' % "".join(out)


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    root = ET.parse(path).getroot()
    rows = []
    for sw in root.findall("software"):
        name = sw.get("name")
        desc = (sw.findtext("description") or "").strip()
        series = ""
        for info in sw.findall("info"):
            if info.get("name") == "series":
                series = info.get("value") or ""
        for part in sw.findall("part"):
            feats = {f.get("name"): f.get("value") for f in part.findall("feature")}
            slot = feats.get("slot", "std")
            for area in part.findall("dataarea"):
                if area.get("name") != "rom":
                    continue
                roms = area.findall("rom")
                if len(roms) != 1:
                    raise SystemExit("%s: expected one <rom> in the rom area" % name)
                crc = int(roms[0].get("crc"), 16)
                size = int(roms[0].get("size"))
                rows.append((crc, size, TYPES[slot], name, desc, series))
    rows.sort()
    print("/* carts_table.h -- GENERATED by tools/carts/make-cart-table.py from MAME's")
    print(" * hash/channelf.xml (CC0-1.0). Identification data only: each Videocart's")
    print(" * CRC-32 and size, the PCB the software list gives it, its short name and")
    print(" * its description. No ROM bytes. Do not edit. */")
    print()
    print("typedef struct {")
    print("    uint32_t crc, size;")
    print("    int type;                   /* enum chf_cart_type */")
    print("    const char *name;           /* the software list's short name */")
    print("    const char *description;")
    print("    const char *series;         /* \"Videocart 10\", or \"\" */")
    print("} chf_softlist_entry;")
    print()
    print("static const chf_softlist_entry k_chf_softlist[] = {")
    for crc, size, typ, name, desc, series in rows:
        print("    { 0x%08xu, %du, %s, %s, %s, %s }," % (crc, size, typ, cstr(name), cstr(desc), cstr(series)))
    print("};")


if __name__ == "__main__":
    main()
