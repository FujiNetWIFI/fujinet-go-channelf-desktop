#!/usr/bin/env python3
"""Generate roms_embedded.c: the recognised BIOS ROMs in a directory, or
nothing at all.

The Channel F console BIOS (two 1K ROMs: a first half, sl31253 or sl90025,
and sl31254) is copyrighted firmware and is not redistributed by this project
(COMPLIANCE.md). --none is therefore the SHIPPING configuration, not an error
path: it emits an empty table, and the machine boots CONFIG on the app's own
stand-in.

With a directory (WITH_CHF_ROMS=ON, a developer build), every file in it --
and every entry of every zip in it, so MAME's channelf.zip can be dropped in
as it is -- whose size and CRC-32 match MAME's table (the same table as
core/src/roms.c) is embedded under MAME's file name, whatever it is called
locally. A 2K file that is a first half followed by sl31254 is split. Anything
else is ignored.

usage: embed-roms.py <out.c> <dir>
       embed-roms.py --none <out.c>
"""

import sys
import zipfile
import zlib
from pathlib import Path

# (size, crc) -> MAME's file name; mirrors s_items[] in core/src/roms.c
KNOWN = {
    (0x400, 0x04694ED9): "sl31253.rom",   # Channel F / Videoplay, first half
    (0x400, 0x015C1E38): "sl90025.rom",   # System II / Videoplay 2, first half
    (0x400, 0x9C047BA3): "sl31254.rom",   # second half, every console
}
HALF = 0x400
MAX_SIZE = 2 * HALF

HEADER = """/* Generated by tools/roms/embed-roms.py -- do not edit.
 * SPDX-License-Identifier: GPL-3.0-or-later
 */
#include "roms_embedded.h"

"""


def candidates(src):
    """Every file in the directory, and every entry of every zip in it."""
    for f in sorted(src.iterdir()) if src.is_dir() else []:
        if not f.is_file():
            continue
        if zipfile.is_zipfile(f):
            with zipfile.ZipFile(f) as z:
                for info in z.infolist():
                    if not info.is_dir() and info.file_size <= MAX_SIZE:
                        yield z.read(info)
        elif f.stat().st_size <= MAX_SIZE:
            yield f.read_bytes()


def known(data):
    return KNOWN.get((len(data), zlib.crc32(data) & 0xFFFFFFFF))


def main():
    args = sys.argv[1:]
    if args and args[0] == "--none":
        if len(args) != 2:
            sys.exit(__doc__)
        Path(args[1]).write_text(
            HEADER
            + "/* Nothing embedded -- the shipping configuration. */\n"
            + "const chf_embedded_rom chf_embedded_roms[1] = { { 0, 0, 0 } };\n"
            + "const unsigned chf_embedded_rom_count = 0;\n")
        return 0

    if len(args) != 2:
        sys.exit(__doc__)
    out, src = Path(args[0]), Path(args[1])
    found = {}
    for data in candidates(src):
        name = known(data)
        if name:
            found.setdefault(name, data)
        elif len(data) == MAX_SIZE:
            # a known first half followed by sl31254
            lo, hi = known(data[:HALF]), known(data[HALF:])
            if lo in ("sl31253.rom", "sl90025.rom") and hi == "sl31254.rom":
                found.setdefault(lo, data[:HALF])
                found.setdefault(hi, data[HALF:])

    body = [HEADER,
            "/* WITH_CHF_ROMS=ON: a developer build. NOT redistributable.\n"
            " * See COMPLIANCE.md. */\n"]
    for i, (name, data) in enumerate(found.items()):
        body.append("static const uint8_t rom%d[%d] = {\n" % (i, len(data)))
        for j in range(0, len(data), 16):
            body.append("    " + ",".join("0x%02X" % b for b in data[j:j + 16]) + ",\n")
        body.append("};\n")
    body.append("\nconst chf_embedded_rom chf_embedded_roms[%d] = {\n" % max(1, len(found)))
    for i, (name, data) in enumerate(found.items()):
        body.append('    { "%s", rom%d, %d },\n' % (name, i, len(data)))
    if not found:
        body.append("    { 0, 0, 0 },\n")
    body.append("};\nconst unsigned chf_embedded_rom_count = %d;\n" % len(found))
    out.write_text("".join(body))
    print("embed-roms: %d image(s): %s" % (len(found), ", ".join(found) or "none"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
