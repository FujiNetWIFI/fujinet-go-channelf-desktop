#!/bin/sh
# build-stub.sh -- assemble core/chf/stub.asm (the Macroassembler AS, CPU
# F3850) into the 2 KiB stand-in BIOS and write core/chf/stub.c from it.
#
#   tools/stub/build-stub.sh                  rewrite core/chf/stub.c
#   tools/stub/build-stub.sh --rompath DIR    also write DIR/channelf/{sl31253,
#                                             sl90025,sl31254}.rom (the image's
#                                             two halves; for MAME: observe.py
#                                             --check and config_golden.py
#                                             --stub-rompath take that DIR)
#   tools/stub/build-stub.sh --check          fail if stub.c is not what stub.asm
#                                             builds (writes nothing)
#
# Needs asl and p2bin (env ASL, P2BIN; default ~/asl/) and python3.
#
# Copyright (C) 2026 Thomas Cherryhomes
# SPDX-License-Identifier: GPL-3.0-or-later

set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
asl=${ASL:-$HOME/asl/asl}
p2bin=${P2BIN:-$HOME/asl/p2bin}
rompath=
check=0

while [ $# -gt 0 ]; do
    case $1 in
    --rompath) rompath=$2; shift 2 ;;
    --check) check=1; shift ;;
    *) echo "usage: $0 [--rompath DIR] [--check]" >&2; exit 2 ;;
    esac
done

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cp "$root/core/chf/stub.asm" "$tmp/stub.asm"
(
    cd "$tmp"
    "$asl" -q -L stub.asm </dev/null >asl.out 2>&1 || { cat asl.out >&2; exit 1; }
    "$p2bin" stub.p stub.bin -r 0x0000-0x07ff -l 0xff </dev/null >/dev/null
)
[ "$(wc -c <"$tmp/stub.bin")" -eq 2048 ] || { echo "build-stub: image is not 2048 bytes" >&2; exit 1; }

python3 -I - "$tmp/stub.bin" "$tmp/stub.lst" "$tmp/stub.c" <<'EOF'
import re
import sys

binp, lstp, outp = sys.argv[1:4]
img = open(binp, "rb").read()

# the bytes the assembler emitted, from the listing: "  29/   0 : 2A 08 00  ..."
used = set()
syms = {}
for line in open(lstp, errors="replace"):
    m = re.match(r"^\s*\d+/\s*([0-9A-F]+) :((?: [0-9A-F]{2})*)(?:  |$)", line)
    if m:
        a = int(m.group(1), 16)
        n = len(m.group(2).split())
        used.update(range(a, a + n))
    m = re.match(r"^\s*(RESET|CLEAR|PUSHK|POPK) :\s+([0-9A-F]+) C", line)
    if m:
        syms[m.group(1)] = int(m.group(2), 16)

runs = []
for a in sorted(used):
    if runs and a == runs[-1][1] + 1:
        runs[-1][1] = a
    else:
        runs.append([a, a])

rows = []
for i in range(0, len(img), 16):
    rows.append("    " + ",".join("0x%02x" % b for b in img[i:i + 16]) + ",")

with open(outp, "w") as f:
    f.write("""/* stub.c -- GENERATED by tools/stub/build-stub.sh from core/chf/stub.asm; do not
 * edit (change the assembly and run the script).
 *
 * The app's own stand-in for the Channel F console's BIOS: $0000-$07FF, written
 * from tools/stub/SPEC.md. It implements the four entry points the FujiNet
 * programs use and nothing else:
 *
 *   $0000  RESET        enters the cartridge at $0802 when [$0800] = $55
 *   $00D0  clear screen (r3 = 0 and the three colours)
 *   $0107  push K
 *   $011E  pop K
 *
 * Bytes the assembly emits (everything else is $FF, an illegal opcode, which
 * parks the machine with "Import BIOS"):
""")
    for a, b in runs:
        f.write(" *   $%04X-$%04X  (%d bytes)\n" % (a, b, b - a + 1))
    f.write(""" *
 * Copyright (C) 2026 Thomas Cherryhomes
 * SPDX-License-Identifier: GPL-3.0-or-later
 */

#include "chf_internal.h"

const uint8_t chf_stub_rom[CF_BIOS_SIZE] = {
""")
    f.write("\n".join(rows) + "\n};\n")
print("stub: %d bytes in %d ranges, %d bytes used" % (len(img), len(runs), len(used)))
EOF

if [ "$check" -eq 1 ]; then
    cmp -s "$tmp/stub.c" "$root/core/chf/stub.c" || { echo "build-stub: core/chf/stub.c is stale" >&2; exit 1; }
    echo "stub.c is up to date"
else
    cp "$tmp/stub.c" "$root/core/chf/stub.c"
    echo "wrote core/chf/stub.c"
fi

if [ -n "$rompath" ]; then
    mkdir -p "$rompath/channelf"
    dd if="$tmp/stub.bin" of="$rompath/channelf/sl31253.rom" bs=1024 count=1 2>/dev/null
    dd if="$tmp/stub.bin" of="$rompath/channelf/sl31254.rom" bs=1024 skip=1 count=1 2>/dev/null
    cp "$rompath/channelf/sl31253.rom" "$rompath/channelf/sl90025.rom"
    echo "wrote $rompath/channelf/{sl31253,sl90025,sl31254}.rom"
fi
