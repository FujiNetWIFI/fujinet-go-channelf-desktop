"""genheader -- write core/tests/bios_contract.h from the observations.

Only state SPEC.md says matters is emitted: for every contract case the
pre-state, the post-state the real BIOS left, and which of it is tier 1 (a
stand-in must match) or tier 2 (real-BIOS leftover; match if cheap).
"""
import biosmodel as bm
from obslib import vram_expand


def _fnv(cells):
    h = 0x811C9DC5
    for x in cells:
        h = ((h ^ (x & 0xFF)) * 0x01000193) & 0xFFFFFFFF
    return h


def _rle(runs):
    out = []
    for v, n in runs:
        out.extend([v] * n)
    return out


ROUTINE_ENUM = {"reset": "CHF_BC_RESET", "clr": "CHF_BC_CLRSCRN", "push": "CHF_BC_PUSHK", "pop": "CHF_BC_POPK"}
FLAG = dict(a="CHF_BC_A", is_="CHF_BC_ISAR", dc0="CHF_BC_DC0", dc1="CHF_BC_DC1", pc1="CHF_BC_PC1",
            vram="CHF_BC_VRAM")


def _bytes(vals, indent="        "):
    lines = []
    for i in range(0, len(vals), 16):
        lines.append(indent + ",".join("0x%02x" % v for v in vals[i:i + 16]))
    return ",\n".join(lines)


def _pre(c, want_vram=True):
    return dict(a=c.a, w=c.w, is_=c.is_, dc0=c.dc0, dc1=c.dc1, pc1=c.pc1, r=list(c.r),
                p0=c.p0, p1=c.p1, p4=c.p4, p5=c.p5, vram=vram_expand(c.vspec) if want_vram else None)


def _post(r, c):
    last = r["io"]["last"]
    return dict(a=r["a"], w=r["w"], is_=r["is"], dc0=r["dc0"], dc1=r["dc1"], pc1=r["pc1"], r=list(r["r"]),
                p0=last.get("0", c.p0), p1=last.get("1", c.p1), p4=last.get("4", c.p4),
                p5=last.get("5", c.p5), vram=_rle(r["vram"]))


def _vram_desc(vspec):
    k = vspec[0]
    if k == "z":
        return "CHF_BC_VRAM_ZERO", 0
    if k == "c":
        return "CHF_BC_VRAM_FILL", int(vspec[1:], 16)
    return "CHF_BC_VRAM_LCG", int(vspec[1:], 16)


def write(path, groups, results, seed, bios_ref, alt=None):
    """results: {bios: (res, hid, stats, boot)}"""
    res = results[bios_ref][0]
    res_alt = results[alt][0] if alt and alt in results else None
    out = []
    A = out.append
    A('''/* bios_contract.h -- GENERATED by tools/stub/observe.py --header (seed %d). Do not edit.
 *
 * What the real Channel F BIOS does at its four entry points that FujiNet's
 * programs use, observed black-box in MAME (first half %s; the other first
 * half, sl90025, differs only in the clear-screen columns, r1 and port 4: see
 * e_vram_fnv_alt and tools/stub/SPEC.md).  A stand-in BIOS is correct when
 * every case below passes.
 *
 * Protocol for a case (see SPEC.md "How to test"):
 *   - RESET:   cartridge with [$0800] = $55 (and a spin loop at $0802).  Load
 *              the pre-state; set A = a, PC1 = pc1; run `JMP $0000`; the
 *              result is the state when control reaches $0802.
 *   - others:  load the pre-state; set A = a, PC1 = pc1 (the return address);
 *              set PC0 = routine entry ($00D0 / $0107 / $011E) -- the state
 *              `PI entry` leaves -- and run until PC0 == pc1.  The result is
 *              the state at that moment.
 *   - pre-state = w (bits 4..0), isar, dc0, dc1, latch[] (port 0,1,4,5 output
 *              latches; the VRAM write registers follow from them), r[0..63],
 *              and VRAM per vram_kind/vram_arg (chf_bios_vram_fill()).
 *   - t1_* mark what must match (tier 1); t2_* what the real BIOS leaves but
 *              FujiNet code cannot rely on (tier 2: warn only).  Everything
 *              else is "don't care".  r[] bytes compare as e_r[] under t1_r/t2_r.
 */
#ifndef CHF_BIOS_CONTRACT_H
#define CHF_BIOS_CONTRACT_H

#include <stdint.h>

enum { CHF_BC_RESET, CHF_BC_CLRSCRN, CHF_BC_PUSHK, CHF_BC_POPK };
enum { CHF_BC_A = 1, CHF_BC_ISAR = 2, CHF_BC_DC0 = 4, CHF_BC_DC1 = 8, CHF_BC_PC1 = 16, CHF_BC_VRAM = 32 };
enum { CHF_BC_VRAM_ZERO, CHF_BC_VRAM_FILL, CHF_BC_VRAM_LCG };

typedef struct {
    uint8_t  routine;
    uint8_t  a;                 /* A at entry */
    uint16_t pc1;               /* PC1 at entry = the return address */
    uint8_t  w, isar;
    uint16_t dc0, dc1;
    uint8_t  latch[4];          /* ports 0, 1, 4, 5 */
    uint8_t  r[64];
    uint8_t  vram_kind;
    uint32_t vram_arg;
    /* after */
    uint8_t  e_a, e_w, e_isar;
    uint16_t e_dc0, e_dc1, e_pc1;
    uint8_t  e_latch[4];
    uint8_t  e_r[64];
    uint32_t e_vram_fnv;        /* FNV-1a 32 over the 8192 cells, row*128+col */
    uint32_t e_vram_fnv_alt;    /* the same for the sl90025 BIOS (clear screen only; else equal) */
    /* what is checked */
    uint8_t  t1_flags, t2_flags;
    uint8_t  t1_w, t2_w;
    uint8_t  t1_latch[4], t2_latch[4];
    uint64_t t1_r, t2_r;
} chf_bios_case;

/* pre-VRAM generator: ZERO -> all 0; FILL -> all vram_arg; LCG -> x = vram_arg;
 * for each cell: x = x * 6364136223846793005 + 1442695040888963407 (mod 2^64);
 * cell = (x >> 33) & 3 */
static inline void chf_bios_vram_fill(uint8_t *cells, int kind, uint32_t arg)
{
    uint64_t x = arg;
    for (int i = 0; i < 8192; i++) {
        if (kind == CHF_BC_VRAM_LCG) {
            x = x * 6364136223846793005ULL + 1442695040888963407ULL;
            cells[i] = (uint8_t)((x >> 33) & 3);
        } else {
            cells[i] = kind == CHF_BC_VRAM_FILL ? (uint8_t)arg : 0;
        }
    }
}

static inline uint32_t chf_bios_vram_fnv(const uint8_t *cells)
{
    uint32_t h = 0x811C9DC5u;
    for (int i = 0; i < 8192; i++) h = (h ^ cells[i]) * 0x01000193u;
    return h;
}
''' % (seed, bios_ref))

    # --- cases --------------------------------------------------------------
    cases = []
    for gname, rt in (("contract_reset", "reset"), ("contract_clr", "clr"),
                      ("contract_push", "push"), ("contract_pop", "pop")):
        for c in groups[gname]:
            r = res[c.id]
            if not r["ok"]:
                raise RuntimeError("contract case %s/%d did not return" % (gname, c.id))
            pre = _pre(c)
            post = _post(r, c)
            post_v = _rle(r["vram"])
            alt_v = _rle(res_alt[c.id]["vram"]) if res_alt else post_v
            tiers = bm.field_tiers(rt, pre)
            t1 = {f for f, t in tiers.items() if t == 1}
            t2 = {f for f, t in tiers.items() if t == 2}

            def wmask(ts):
                return (0x10 if "w.I" in ts else 0) | (0x0F if "w.flags" in ts else 0)

            def latchm(ts):
                return [0xFF if "p0" in ts else 0, 0xFF if "p1" in ts else 0, 0xFF if "p4" in ts else 0,
                        (0xC0 if "p5.sound" in ts else 0) | (0x3F if "p5.row" in ts else 0)]

            def flagm(ts):
                f = [FLAG[x] for x in ("a", "is_", "dc0", "dc1", "pc1", "vram") if x in ts]
                return " | ".join(f) if f else "0"
            vk, va = _vram_desc(c.vspec)
            t1_r = sum(1 << k for k in range(64) if "r%d" % k in t1)
            t2_r = sum(1 << k for k in range(64) if "r%d" % k in t2)
            cases.append((gname, c, rt, pre, post, vk, va, _fnv(post_v), _fnv(alt_v), flagm(t1), flagm(t2),
                          wmask(t1), wmask(t2), latchm(t1), latchm(t2), t1_r, t2_r))

    A("\nstatic const chf_bios_case chf_bios_cases[] = {")
    for (gname, c, rt, pre, post, vk, va, ev, eva, f1, f2, w1, w2, l1, l2, r1, r2) in cases:
        A("    { /* %s #%d */" % (gname, c.id))
        A("    %s, 0x%02x, 0x%04x, 0x%02x, 0x%02x, 0x%04x, 0x%04x," % (
            ROUTINE_ENUM[rt], c.a, c.pc1, c.w, c.is_, c.dc0, c.dc1))
        A("    {0x%02x,0x%02x,0x%02x,0x%02x}," % (c.p0, c.p1, c.p4, c.p5))
        A("    {\n%s\n    }," % _bytes(c.r))
        A("    %s, 0x%x," % (vk, va))
        A("    0x%02x, 0x%02x, 0x%02x, 0x%04x, 0x%04x, 0x%04x," % (
            post["a"], post["w"], post["is_"], post["dc0"], post["dc1"], post["pc1"]))
        A("    {0x%02x,0x%02x,0x%02x,0x%02x}," % (post["p0"], post["p1"], post["p4"], post["p5"]))
        A("    {\n%s\n    }," % _bytes(post["r"]))
        A("    0x%08xu, 0x%08xu," % (ev, eva))
        A("    %s, %s, 0x%02x, 0x%02x, {0x%02x,0x%02x,0x%02x,0x%02x}, {0x%02x,0x%02x,0x%02x,0x%02x}, 0x%016xull, 0x%016xull }," % (
            f1, f2, w1, w2, l1[0], l1[1], l1[2], l1[3], l2[0], l2[1], l2[2], l2[3], r1, r2))
    A("};\n#define CHF_BIOS_NCASES (sizeof chf_bios_cases / sizeof chf_bios_cases[0])\n")

    # --- r3 table -------------------------------------------------------------
    sweep = groups["clr_r3sweepA"]
    base = sweep[0]
    A("/* Clear screen with every r3 (mode A: r31 & 3 == 0): VRAM digest after the call, for the fixed base\n"
      " * state below with r3 replaced.  Only r3 = $00/$40/$80/$C0 are tier 1; the rest are informational\n"
      " * (their behaviour depends on more of the scratchpad; see SPEC.md).  [0] = sl31253, [1] = sl90025. */")
    vk, va = _vram_desc(base.vspec)
    A("static const struct { uint8_t a; uint16_t pc1; uint8_t w, isar; uint16_t dc0, dc1; uint8_t latch[4]; uint8_t r[64];")
    A("                      uint8_t vram_kind; uint32_t vram_arg; } chf_bios_clr_r3_base = {")
    A("    0x00, 0x%04x, 0x%02x, 0x%02x, 0x%04x, 0x%04x, {0x%02x,0x%02x,0x%02x,0x%02x}," % (
        base.pc1, base.w, base.is_, base.dc0, base.dc1, base.p0, base.p1, base.p4, base.p5))
    A("    {\n%s\n    }," % _bytes([0 if k == 3 else x for k, x in enumerate(base.r)]))
    A("    %s, 0x%x };" % (vk, va))
    A("static const uint32_t chf_bios_clr_r3_fnv[256][2] = {")
    row = []
    for i, c in enumerate(sweep):
        f0 = _fnv(_rle(res[c.id]["vram"]))
        f1 = _fnv(_rle(res_alt[c.id]["vram"])) if res_alt else f0
        row.append("{0x%08xu,0x%08xu}" % (f0, f1))
    for i in range(0, 256, 4):
        A("    " + ", ".join(row[i:i + 4]) + ",")
    A("};\n\n#endif /* CHF_BIOS_CONTRACT_H */")
    open(path, "w").write("\n".join(out) + "\n")
